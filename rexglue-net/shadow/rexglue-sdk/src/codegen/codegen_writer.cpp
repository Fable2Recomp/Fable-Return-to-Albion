bool CodegenWriter::write(bool force) {
  deletedFiles_.clear();
  writtenFiles_.clear();
  unchangedFiles_.clear();
  pendingWrites.clear();

  if (ctx_.errors.HasErrors() && !force) {
    REXCODEGEN_ERROR("Code generation blocked: {} validation errors. Use --force to override.",
                     ctx_.errors.Count());
    return false;
  }

  std::filesystem::path outputPath = ctx_.configDir() / config().outDirectoryPath;
  REXCODEGEN_TRACE("Output path: {}", outputPath.string());
  std::filesystem::create_directories(outputPath);

  REXCODEGEN_TRACE("Recompile: starting");
  out.reserve(kOutputBufferReserveSize);

  // Build sorted function list using graph().functionsByBase() (already ordered in O(N)!)
  std::vector<const FunctionNode*> functions;
  functions.reserve(graph().functionCount());
  for (const auto& [addr, nodePtr] : graph().functionsByBase()) {
    functions.push_back(nodePtr);
  }

  // Build rexcrt reverse map and rename graph nodes
  std::unordered_map<uint32_t, std::string> rexcrtByAddr;
  for (const auto& [name, addr] : config().rexcrtFunctions) {
    auto crtName = fmt::format("rexcrt_{}", name);
    rexcrtByAddr[addr] = crtName;
    if (auto* node = graph().getFunction(addr)) {
      node->setName(std::move(crtName));
    }
  }

  const std::string& projectName = config().projectName;
  const bool hasCustomTemplateDir = !config().templateDir.empty();

  TemplateRegistry registry;
  if (hasCustomTemplateDir)
    registry.loadOverrides(config().templateDir);

  size_t codeMin = 0;
  size_t codeMax = 0;
  computeCodeBounds(ctx_, codeMin, codeMax);
  auto symbolEntries = buildSymbolEntries(ctx_, functions, rexcrtByAddr, codeMin);
  auto tmplData = buildTemplateData(ctx_, symbolEntries, codeMin, codeMax, hasCustomTemplateDir);

  // Generate {project}_pch.h
  REXCODEGEN_TRACE("Recompile: generating {}_pch.h", projectName);
  out = renderWithJson(registry, "codegen/pch_h", tmplData);
  SaveCurrentOutData(fmt::format("{}_pch.h", projectName));

  // Generate {project}_funcs.h
  REXCODEGEN_TRACE("Recompile: generating {}_funcs.h", projectName);
  out = hasCustomTemplateDir ? renderWithJson(registry, "codegen/funcs_h", tmplData)
                             : formatFuncsHeader(projectName, symbolEntries);
  SaveCurrentOutData(fmt::format("{}_funcs.h", projectName));

  // Generate {project}_init.h
  REXCODEGEN_TRACE("Recompile: generating {}_init.h", projectName);
  out = renderWithJson(registry, "codegen/init_h", tmplData);
  SaveCurrentOutData(fmt::format("{}_init.h", projectName));

  // Generate {project}_init.cpp
  REXCODEGEN_TRACE("Recompile: generating {}_init.cpp", projectName);
  out = hasCustomTemplateDir ? renderWithJson(registry, "codegen/init_cpp", tmplData)
                             : formatInitCpp(ctx_, symbolEntries);
  SaveCurrentOutData(fmt::format("{}_init.cpp", projectName));

  // Generate {project}_register.cpp
  REXCODEGEN_TRACE("Recompile: generating {}_register.cpp", projectName);
  tmplData["is_dll"] = ctx_.isDllModule();
  out = hasCustomTemplateDir ? renderWithJson(registry, "codegen/register_cpp", tmplData)
                             : formatRegisterCpp(ctx_);
  SaveCurrentOutData(fmt::format("{}_register.cpp", projectName));

  // Filter out imports and rexcrt functions before recompilation
  std::erase_if(functions, [](const FunctionNode* fn) {
    return fn->authority() == FunctionAuthority::IMPORT;
  });
  std::erase_if(functions, [&rexcrtByAddr](const FunctionNode* fn) {
    return rexcrtByAddr.contains(static_cast<uint32_t>(fn->base()));
  });

  REXCODEGEN_TRACE("Recompiling {} functions...", functions.size());

  const size_t fnCount = functions.size();
  std::vector<std::string> bodies(fnCount);
  std::vector<FunctionSize> sizes(fnCount);
  std::vector<std::unordered_set<std::string>> references(fnCount);

  const size_t maxFileBytes = REXCVAR_GET(max_file_size_bytes);
  const uint32_t entryPoint = static_cast<uint32_t>(analysisState().entryPoint);
  auto* exportResolver = runtime_ ? runtime_->export_resolver() : nullptr;

  auto emitRange = [&](size_t startIdx, size_t endIdx, EmitContext& localCtx,
                       std::unordered_set<std::string>& localReferenced) {
    for (size_t i = startIdx; i < endIdx; ++i) {
      const FunctionNode* fn = functions[i];
      localReferenced.clear();
      std::string code = fn->emitCpp(localCtx);
      if (code.size() > maxFileBytes) {
        REXCODEGEN_DEBUG("Function 0x{:08X} is {} bytes, exceeds max_file_size_bytes ({})",
                         fn->base(), code.size(), maxFileBytes);
      }
      sizes[i] = {static_cast<uint32_t>(fn->base()), code.size()};
      bodies[i] = std::move(code);
      references[i] = localReferenced;
    }
  };

  if (fnCount > 0) {
    // Emit index 0 on the calling thread first to initialize function-local dispatch tables cleanly.
    {
      std::unordered_set<std::string> firstReferenced;
      EmitContext firstCtx{binary(), config(), graph(), entryPoint, exportResolver,
                           &firstReferenced};
      emitRange(0, 1, firstCtx, firstReferenced);
    }

    if (fnCount > 1) {
      constexpr size_t kBatchSize = 64;
      unsigned int hw = std::thread::hardware_concurrency();
      size_t workerCount =
          (fnCount >= 128 && hw > 1) ? std::min<size_t>(hw, (fnCount + kBatchSize - 1) / kBatchSize)
                                     : 1;

      std::atomic<size_t> nextIndex{1};
      auto workerLoop = [&]() {
        std::unordered_set<std::string> localReferenced;
        EmitContext localCtx{binary(), config(), graph(), entryPoint, exportResolver,
                             &localReferenced};
        while (true) {
          size_t begin = nextIndex.fetch_add(kBatchSize, std::memory_order_relaxed);
          if (begin >= fnCount)
            break;
          size_t end = std::min(fnCount, begin + kBatchSize);
          emitRange(begin, end, localCtx, localReferenced);
        }
      };

      if (workerCount <= 1) {
        workerLoop();
      } else {
        std::vector<std::thread> workers;
        workers.reserve(workerCount - 1);
        for (size_t w = 1; w < workerCount; ++w) {
          workers.emplace_back(workerLoop);
        }
        workerLoop();
        for (auto& t : workers) {
          t.join();
        }
      }
    }
  }

  auto partition = OutputPartition::Load(outputPath / kPartitionFileName);
  auto buckets = partition.Assign(sizes, maxFileBytes);

  const size_t baseWriteSlot = pendingWrites.size();
  const size_t bucketCount = buckets.size();
  pendingWrites.resize(baseWriteSlot + bucketCount * 2);

  if (bucketCount > 0) {
    constexpr size_t kBucketBatch = 8;
    unsigned int hw = std::thread::hardware_concurrency();
    size_t workerCount =
        (bucketCount >= 16 && hw > 1)
            ? std::min<size_t>(hw, (bucketCount + kBucketBatch - 1) / kBucketBatch)
            : 1;

    std::atomic<size_t> nextBucket{0};
    auto assembleBuckets = [&]() {
      while (true) {
        size_t begin = nextBucket.fetch_add(kBucketBatch, std::memory_order_relaxed);
        if (begin >= bucketCount)
          break;
        size_t end = std::min(bucketCount, begin + kBucketBatch);
        for (size_t index = begin; index < end; ++index) {
          size_t slot = baseWriteSlot + index * 2;
          pendingWrites[slot] = {
              fmt::format("{}_funcs.{}.h", projectName, index),
              formatBucketHeader(projectName, buckets[index], references)};
          pendingWrites[slot + 1] = {
              fmt::format("{}_recomp.{}.cpp", projectName, index),
              formatBucketSource(projectName, index, buckets[index], bodies)};
        }
      }
    };

    if (workerCount <= 1) {
      assembleBuckets();
    } else {
      std::vector<std::thread> workers;
      workers.reserve(workerCount - 1);
      for (size_t w = 1; w < workerCount; ++w) {
        workers.emplace_back(assembleBuckets);
      }
      assembleBuckets();
      for (auto& t : workers) {
        t.join();
      }
    }
  }

  out = partition.Serialize();
  SaveCurrentOutData(kPartitionFileName);

  REXCODEGEN_TRACE("Recompilation complete.");

  // Generate sources.cmake
  REXCODEGEN_TRACE("Recompile: generating sources.cmake");
  {
    auto& recompFiles = tmplData["recomp_files"];
    recompFiles = nlohmann::json::array();
    for (size_t i = 0; i < buckets.size(); ++i) {
      recompFiles.push_back(fmt::format("{}_recomp.{}.cpp", projectName, i));
    }
    out = renderWithJson(registry, "codegen/sources_cmake", tmplData);
    SaveCurrentOutData("sources.cmake");
  }

  return FlushPendingWrites();
}

void CodegenWriter::SaveCurrentOutData(const std::string_view name) {
  if (!out.empty()) {
    pendingWrites.emplace_back(std::string(name), std::move(out));
    out.clear();
  }
}

bool CodegenWriter::FlushPendingWrites() {
  std::filesystem::path outputPath = ctx_.configDir() / config().outDirectoryPath;

  const size_t totalFiles = pendingWrites.size();
  std::vector<WriteOutcome> outcomes(totalFiles, WriteOutcome::Failed);

  std::unordered_set<std::string> emitted;
  emitted.reserve(totalFiles);
  for (const auto& [filename, _] : pendingWrites) {
    emitted.insert(filename);
  }

  if (totalFiles > 0) {
    constexpr size_t kWriteBatch = 8;
    unsigned int hw = std::thread::hardware_concurrency();
    size_t workerCount =
        (totalFiles >= 16 && hw > 1)
            ? std::min<size_t>(std::min<unsigned int>(hw, 16u),
                               (totalFiles + kWriteBatch - 1) / kWriteBatch)
            : 1;

    std::atomic<size_t> nextFile{0};
    auto flushWorker = [&]() {
      while (true) {
        size_t begin = nextFile.fetch_add(kWriteBatch, std::memory_order_relaxed);
        if (begin >= totalFiles)
          break;
        size_t end = std::min(totalFiles, begin + kWriteBatch);
        for (size_t i = begin; i < end; ++i) {
          const auto& [filename, content] = pendingWrites[i];
          outcomes[i] = WriteIfChanged(outputPath / filename, content);
        }
      }
    };

    if (workerCount <= 1) {
      flushWorker();
    } else {
      std::vector<std::thread> workers;
      workers.reserve(workerCount - 1);
      for (size_t w = 1; w < workerCount; ++w) {
        workers.emplace_back(flushWorker);
      }
      flushWorker();
      for (auto& t : workers) {
        t.join();
      }
    }
  }

  bool ok = true;
  for (size_t i = 0; i < totalFiles; ++i) {
    const auto& [filename, content] = pendingWrites[i];
    auto filePath = outputPath / filename;
    switch (outcomes[i]) {
      case WriteOutcome::Failed:
        REXCODEGEN_ERROR("Failed to write {}", filePath.string());
        ok = false;
        break;
      case WriteOutcome::Unchanged:
        REXCODEGEN_TRACE("Unchanged, skipping write: {}", filePath.string());
        unchangedFiles_.push_back(filename);
        break;
      case WriteOutcome::Written:
        REXCODEGEN_TRACE("Wrote {} bytes to {}", content.size(), filePath.string());
        writtenFiles_.push_back(filename);
        break;
    }
  }

  for (const auto& entry : std::filesystem::directory_iterator(outputPath)) {
    if (!entry.is_regular_file())
      continue;
    auto filename = entry.path().filename().string();
    if (emitted.contains(filename))
      continue;
    if (!IsGeneratedOutputName(filename, config().projectName))
      continue;

    std::error_code ec;
    std::filesystem::remove(entry.path(), ec);
    if (ec) {
      REXCODEGEN_ERROR("Failed to delete stale output {}: {}", entry.path().string(), ec.message());
      continue;
    }
    REXCODEGEN_TRACE("Deleted stale output: {}", entry.path().string());
    deletedFiles_.push_back(filename);
  }

  pendingWrites.clear();
  return ok;
}

