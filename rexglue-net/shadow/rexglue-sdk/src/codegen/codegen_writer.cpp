struct FunctionSymbolEntry {
  uint32_t base;
  std::string name;
  bool isRexcrt;
  bool belowCodeBase;
  bool isImport;

  bool includeInTable() const { return !belowCodeBase || isImport; }
};

void computeCodeBounds(const rex::codegen::CodegenContext& ctx, size_t& codeMin, size_t& codeMax) {
  codeMin = ~size_t(0);
  codeMax = 0;
  for (const auto& section : ctx.binary().sections()) {
    if (section.executable) {
      if (section.baseAddress < codeMin)
        codeMin = section.baseAddress;
      if ((section.baseAddress + section.size) > codeMax)
        codeMax = section.baseAddress + section.size;
    }
  }
}

std::vector<FunctionSymbolEntry> buildSymbolEntries(
    const rex::codegen::CodegenContext& ctx,
    const std::vector<const rex::codegen::FunctionNode*>& functions,
    const std::unordered_map<uint32_t, std::string>& rexcrtByAddr, size_t codeMin) {
  std::vector<FunctionSymbolEntry> entries;
  entries.reserve(functions.size());

  const uint64_t entryPoint = ctx.analysisState().entryPoint;
  for (const auto* fn : functions) {
    FunctionSymbolEntry entry{};
    entry.base = static_cast<uint32_t>(fn->base());
    entry.belowCodeBase = (fn->base() < codeMin);
    entry.isImport = (fn->authority() == rex::codegen::FunctionAuthority::IMPORT);

    auto crtIt = rexcrtByAddr.find(entry.base);
    if (crtIt != rexcrtByAddr.end()) {
      entry.name = crtIt->second;
      entry.isRexcrt = true;
    } else if (fn->base() == entryPoint) {
      entry.name = "xstart";
    } else if (!fn->name().empty()) {
      entry.name = fn->name();
    } else {
      entry.name = fmt::format("sub_{:08X}", entry.base);
    }

    entries.push_back(std::move(entry));
  }

  return entries;
}

nlohmann::json buildTemplateData(const rex::codegen::CodegenContext& ctx,
                                 const std::vector<FunctionSymbolEntry>& entries, size_t codeMin,
                                 size_t codeMax, bool includeFunctionArray) {
  const auto& cfg = ctx.Config();

  nlohmann::json functionsJson = nlohmann::json::array();
  if (includeFunctionArray) {
    for (const auto& entry : entries) {
      functionsJson.push_back({
          {"address", fmt::format("0x{:X}", entry.base)},
          {"name", entry.name},
          {"is_rexcrt", entry.isRexcrt},
          {"below_code_base", entry.belowCodeBase},
          {"is_import", entry.isImport},
      });
    }
  }

  nlohmann::json configFlags = {
      {"skip_lr", cfg.skipLr},
      {"ctr_as_local", cfg.ctrAsLocalVariable},
      {"xer_as_local", cfg.xerAsLocalVariable},
      {"reserved_as_local", cfg.reservedRegisterAsLocalVariable},
      {"skip_msr", cfg.skipMsr},
      {"cr_as_local", cfg.crRegistersAsLocalVariables},
      {"non_argument_as_local", cfg.nonArgumentRegistersAsLocalVariables},
      {"non_volatile_as_local", cfg.nonVolatileRegistersAsLocalVariables},
  };

  return {
      {"project", cfg.projectName},
      {"image_base", fmt::format("0x{:X}", ctx.binary().baseAddress())},
      {"image_size", fmt::format("0x{:X}", ctx.binary().imageSize())},
      {"code_base", fmt::format("0x{:X}", codeMin)},
      {"code_size", fmt::format("0x{:X}", codeMax - codeMin)},
      {"rexcrt_heap", cfg.rexcrtFunctions.contains("RtlAllocateHeap") ? 1 : 0},
      {"thunk_reserve_size", fmt::format("0x{:X}", 0x10000u)},
      {"has_dll_modules", ctx.hasDllModules()},
      {"is_dll", ctx.isDllModule()},
      {"config_flags", configFlags},
      {"functions", std::move(functionsJson)},
      {"recomp_files", nlohmann::json::array()},
  };
}

std::string formatFuncsHeader(std::string_view projectName,
                              const std::vector<FunctionSymbolEntry>& entries) {
  std::string buf;
  buf.reserve(entries.size() * 34 + 192);
  fmt::format_to(std::back_inserter(buf),
                 "// Generated by rexglue\n"
                 "// DO NOT EDIT - this file is auto-generated\n"
                 "#pragma once\n\n"
                 "#include \"{}_pch.h\"\n\n"
                 "//=============================================================================\n"
                 "// Function Declarations\n"
                 "//=============================================================================\n\n",
                 projectName);
  for (const auto& entry : entries) {
    fmt::format_to(std::back_inserter(buf), "DECLARE_REX_FUNC({});\n", entry.name);
  }
  return buf;
}

std::string formatInitCpp(const rex::codegen::CodegenContext& ctx,
                          const std::vector<FunctionSymbolEntry>& entries) {
  const auto& cfg = ctx.Config();
  const std::string& projectName = cfg.projectName;
  const bool registerModules = ctx.hasDllModules() && !ctx.isDllModule();

  std::string buf;
  buf.reserve(entries.size() * 64 + 1024);
  fmt::format_to(std::back_inserter(buf),
                 "// Generated by rexglue\n"
                 "// DO NOT EDIT - this file is auto-generated\n\n"
                 "#include \"{}_pch.h\"\n\n",
                 projectName);

  for (const auto& entry : entries) {
    if (entry.includeInTable()) {
      fmt::format_to(std::back_inserter(buf), "REX_EXTERN({});\n", entry.name);
    }
  }
  buf += '\n';

  if (registerModules) {
    buf += "void RegisterRecompiledModules(rex::system::KernelState*);\n\n";
  }

  fmt::format_to(std::back_inserter(buf),
                 "const rex::PPCImageInfo PPCImageConfig = {{\n"
                 "    .code_base = REX_CODE_BASE,\n"
                 "    .code_size = REX_CODE_SIZE,\n"
                 "    .image_base = REX_IMAGE_BASE,\n"
                 "    .image_size = REX_IMAGE_SIZE,\n"
                 "    .func_mappings = PPCFuncMappings,\n"
                 "    .rexcrt_heap = REXCRT_HEAP,\n");
  if (registerModules) {
    buf += "    .register_modules = RegisterRecompiledModules,\n";
  }
  fmt::format_to(std::back_inserter(buf),
                 "    .codegen_flags = {{\n"
                 "        .skip_lr = {},\n"
                 "        .ctr_as_local = {},\n"
                 "        .xer_as_local = {},\n"
                 "        .reserved_as_local = {},\n"
                 "        .skip_msr = {},\n"
                 "        .cr_as_local = {},\n"
                 "        .non_argument_as_local = {},\n"
                 "        .non_volatile_as_local = {},\n"
                 "    }},\n"
                 "}};\n\n"
                 "PPCFuncMapping PPCFuncMappings[] = {{\n",
                 cfg.skipLr, cfg.ctrAsLocalVariable, cfg.xerAsLocalVariable,
                 cfg.reservedRegisterAsLocalVariable, cfg.skipMsr, cfg.crRegistersAsLocalVariables,
                 cfg.nonArgumentRegistersAsLocalVariables, cfg.nonVolatileRegistersAsLocalVariables);

  for (const auto& entry : entries) {
    if (entry.includeInTable()) {
      fmt::format_to(std::back_inserter(buf), "\t{{ 0x{:X}, {} }},\n", entry.base, entry.name);
    }
  }
  buf += "\t{ 0, nullptr }\n};\n";
  return buf;
}

std::string formatRegisterCpp(const rex::codegen::CodegenContext& ctx) {
  const std::string& projectName = ctx.Config().projectName;
  const bool isDll = ctx.isDllModule();

  std::string buf;
  buf.reserve(1024);
  fmt::format_to(std::back_inserter(buf),
                 "//=============================================================================\n"
                 "// ReXGlue Generated - {} Function Registration\n"
                 "//=============================================================================\n\n"
                 "#include \"{}_pch.h\"\n"
                 "#include <rex/system/function_dispatcher.h>\n\n",
                 projectName, projectName);

  if (isDll) {
    buf +=
        "#ifdef _WIN32\n"
        "#define REX_MODULE_EXPORT __declspec(dllexport)\n"
        "#else\n"
        "#define REX_MODULE_EXPORT __attribute__((visibility(\"default\")))\n"
        "#endif\n\n"
        "extern \"C\" REX_MODULE_EXPORT\n"
        "void ReXModule_Register(rex::runtime::IModuleRegistrar* registrar) {\n";
  } else {
    fmt::format_to(std::back_inserter(buf),
                   "void {}_RegisterFunctions(rex::runtime::IModuleRegistrar* registrar) {{\n",
                   projectName);
  }

  buf +=
      "  for (const PPCFuncMapping* m = PPCFuncMappings; m->guest != 0 || m->host != nullptr; ++m) {\n"
      "    if (m->host != nullptr) {\n"
      "      registrar->SetFunction(static_cast<uint32_t>(m->guest), m->host);\n"
      "    }\n"
      "  }\n"
      "}\n";

  if (isDll) {
    buf +=
        "\n// The runtime uses this baked layout for the dispatch table. It must match the\n"
        "// constants used by this module's REX_LOOKUP_FUNC macro.\n"
        "extern \"C\" REX_MODULE_EXPORT\n"
        "const rex::PPCImageInfo* ReXModule_GetImageInfo() {\n"
        "  return &PPCImageConfig;\n"
        "}\n";
  }

  return buf;
}

std::string formatBucketHeader(std::string_view projectName,
                               const std::vector<size_t>& bucketEntries,
                               const std::vector<std::unordered_set<std::string>>& references) {
  std::unordered_set<std::string> needed;
  for (size_t entry : bucketEntries) {
    needed.insert(references[entry].begin(), references[entry].end());
  }

  std::vector<std::string> ordered(needed.begin(), needed.end());
  std::sort(ordered.begin(), ordered.end());

  std::string buf;
  buf.reserve(ordered.size() * 34 + 128);
  fmt::format_to(std::back_inserter(buf), "#pragma once\n\n#include \"{}_pch.h\"\n\n", projectName);
  for (const auto& name : ordered) {
    fmt::format_to(std::back_inserter(buf), "DECLARE_REX_FUNC({});\n", name);
  }
  return buf;
}

std::string formatBucketSource(std::string_view projectName, size_t index,
                               const std::vector<size_t>& bucketEntries,
                               const std::vector<std::string>& bodies) {
  size_t totalBytes = 64;
  for (size_t entry : bucketEntries) {
    totalBytes += bodies[entry].size();
  }

  std::string buf;
  buf.reserve(totalBytes);
  fmt::format_to(std::back_inserter(buf), "#include \"{}_funcs.{}.h\"\n\n", projectName, index);
  for (size_t entry : bucketEntries) {
    buf += bodies[entry];
  }
  return buf;
}

