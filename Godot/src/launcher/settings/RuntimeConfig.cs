using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Text;

namespace Refii.Launcher.Core;

public static class RuntimeConfig
{
    public static SortedDictionary<string, string> ReadValues(string configPath)
    {
        var values = new SortedDictionary<string, string>(StringComparer.Ordinal);
        if (!File.Exists(configPath))
        {
            return values;
        }

        string section = string.Empty;
        foreach (string rawLine in File.ReadLines(configPath))
        {
            string line = StripTomlComment(rawLine).Trim();
            if (line.Length == 0)
            {
                continue;
            }

            if (line[0] == '[' && line[^1] == ']')
            {
                section = line.Substring(1, line.Length - 2).Trim().Replace('.', '_');
                continue;
            }

            int equals = line.IndexOf('=');
            if (equals < 0)
            {
                continue;
            }

            string key = line.Substring(0, equals).Trim();
            string value = line[(equals + 1)..].Trim();
            if (key.Length == 0)
            {
                continue;
            }

            if (section.Length != 0)
            {
                key = section + "_" + key;
            }

            string unquoted = UnquoteTomlString(value);
            values[key] = key == "game_data_root"
                ? NormalizeGameDataRootValue(unquoted, configPath)
                : unquoted;
        }

        return values;
    }

    public static bool WriteValues(
        string configPath,
        IReadOnlyDictionary<string, string> values,
        out string error)
    {
        error = string.Empty;
        try
        {
            string? parent = Path.GetDirectoryName(configPath);
            if (!string.IsNullOrEmpty(parent))
            {
                Directory.CreateDirectory(parent!);
            }

            var builder = new StringBuilder();
            builder.Append("# Runtime config generated by the launcher.\n");
            builder.Append("# Every setting the launcher offers is written explicitly.\n\n");

            var written = new HashSet<string>(StringComparer.Ordinal);
            string currentCategory = string.Empty;
            foreach (RuntimeCVarDefinition definition in RuntimeCVarSet.All)
            {
                if (!ShouldWriteCVar(definition))
                {
                    continue;
                }

                if (definition.Category != currentCategory)
                {
                    builder.Append('\n').Append("# ").Append(definition.Category).Append('\n');
                    currentCategory = definition.Category;
                }

                string rawValue = values.TryGetValue(definition.Name, out string? existing)
                    ? existing
                    : definition.DefaultValue;

                if (!string.IsNullOrEmpty(definition.Description))
                {
                    builder.Append("# ").Append(definition.Description).Append('\n');
                }

                builder.Append(definition.Name)
                    .Append(" = ")
                    .Append(FormatTomlValue(definition, rawValue))
                    .Append('\n');

                written.Add(definition.Name);
            }

            AppendUnrecognised(builder, values, written);

            File.WriteAllText(configPath, builder.ToString(), new UTF8Encoding(false));
            return true;
        }
        catch (Exception exception)
        {
            error = exception.Message;
            return false;
        }
    }

    public static bool EnsureDefaults(string configPath, out string error)
    {
        error = string.Empty;
        SortedDictionary<string, string> values = ReadValues(configPath);
        bool changed = !File.Exists(configPath);

        if (ShouldUsePackagedRuntimeDefaults())
        {
            string packagedGameDataRoot = Installer.GetInstallBasePath();
            string packagedUserDataRoot = LauncherPaths.GetRuntimeDataRootDirectory();

            changed |= UpdateDefaultPath(values, "game_data_root", "assets", ToGeneric(packagedGameDataRoot));
            changed |= UpdateDefaultPath(values, "user_data_root", "assets/save", ToGeneric(packagedUserDataRoot));
        }
        else
        {
            string baseRoot = Installer.GetInstallBasePath();
            string configDirectory = Path.GetDirectoryName(configPath) ?? string.Empty;

            foreach ((string key, string legacyDefault) in AssetRelativeRoots)
            {
                string relative = legacyDefault.Length > AssetsPrefix.Length
                    ? legacyDefault[(AssetsPrefix.Length + 1)..]
                    : string.Empty;
                string absolute = relative.Length == 0
                    ? baseRoot
                    : Path.Combine(baseRoot, relative.Replace('/', Path.DirectorySeparatorChar));

                string legacy = key == "game_data_root" && configDirectory.Length != 0
                    ? ToGeneric(LauncherPaths.Normalize(Path.Combine(configDirectory, AssetsPrefix)))
                    : legacyDefault;

                changed |= UpdateDefaultPath(values, key, legacy, ToGeneric(absolute));
            }
        }

        // ONE CACHE CONTAINER, STATED RATHER THAN DERIVED.
        //
        // cache_root is a real cvar — rex_app.cpp reads it and uses it when non-empty — but
        // nothing ever WROTE it, so the SDK fell back to deriving it from user_data_root and the
        // guest cached into assets/save/cache. That put regenerable data inside the one directory
        // a player can never regenerate, and split the app's cache in two: the guest's under
        // save, the managed side's somewhere else entirely.
        //
        // Anchored on the same Engine_AppRoot.CacheDirectory the texture cache uses, so the guest
        // and Godot agree and clearing derived data is one folder. UpdateDefaultPath leaves a
        // value the player set themselves alone.
        changed |= UpdateDefaultPath(
            values,
            "cache_root",
            ToGeneric(Path.Combine(Installer.GetInstallBasePath(), "assets", "save", "cache")),
            ToGeneric(Refii.Core.Engine_AppRoot.CacheDirectory));

        changed |= AdoptFixtureShadowDefault(values);

        return changed ? WriteValues(configPath, values, out error) : true;
    }

    /// <summary>
    /// `placed_light_shadows` went from default false to default true, and this file states
    /// every setting explicitly, so an existing install would hold the old default for ever.
    /// ONE SHOT: `placed_light_shadows_world` arrived in the same change and the write this
    /// triggers adds it, so its absence marks a file from before — a player who turns fixture
    /// shadows off afterwards keeps them off.
    /// </summary>
    private static bool AdoptFixtureShadowDefault(IDictionary<string, string> values)
    {
        if (values.Count == 0 || values.ContainsKey("placed_light_shadows_world"))
        {
            return false;
        }

        values["placed_light_shadows_world"] = "false";
        values["placed_light_shadows"] = "true";
        return true;
    }

    private const string AssetsPrefix = "assets";

    private static readonly (string Key, string LegacyDefault)[] AssetRelativeRoots =
    {
        ("game_data_root", "assets"),
        ("user_data_root", "assets/save"),
    };

    private static bool ShouldUsePackagedRuntimeDefaults() => LauncherPaths.UseLinuxUserDataRoot();

    private static bool UpdateDefaultPath(
        IDictionary<string, string> values,
        string key,
        string legacyDefault,
        string packagedValue)
    {
        bool present = values.TryGetValue(key, out string? current);
        if (!present || string.IsNullOrEmpty(current) || current == legacyDefault)
        {
            if (!present || current != packagedValue)
            {
                values[key] = packagedValue;
                return true;
            }
        }

        return false;
    }

    /// <summary>
    /// Whether a setting is offered in the panel. Nothing depends on another setting's value
    /// any more: the last such gate was the renderer backend, and there is no renderer to pick.
    /// </summary>
    public static bool ShouldShowCVar(RuntimeCVarDefinition definition) =>
        !IsRetiredNativeCategory(definition.Category) || IsDisplayCVar(definition.Name);

    /// <summary>
    /// Whether a setting is written to refii.toml — the same question as showing it. A setting
    /// nobody can act on should not sit in the file implying it does something.
    /// </summary>
    public static bool ShouldWriteCVar(RuntimeCVarDefinition definition) => ShouldShowCVar(definition);

    /// <summary>The settings panel's name for everything the player tunes about the picture.</summary>
    public const string DisplayCategory = "Display";

    /// <summary>
    /// Categories that belonged to the native renderer and its window, and are now dead.
    ///
    /// Godot draws the game — there is no backend to choose, no Xenia, Plume, D3D12 or Vulkan
    /// device of ours to configure, no RenderDoc or ImGui hooked into one, no presenter to
    /// letterbox, and the guest's own input and audio paths are not the ones running. Embedded,
    /// the host bridge fixes the guest's backend through the environment and the guest never
    /// reads refii.toml, so nothing in these categories could reach it anyway. Retiring them
    /// here hides them AND stops them being written, because `ShouldWriteCVar` is this same
    /// predicate.
    /// </summary>
    private static bool IsRetiredNativeCategory(string category) =>
        category is "Renderer" or "Renderer/ImGui" or "Renderer/Debug"
            or "Renderer/Vulkan" or "Renderer/D3D12" or "Renderer/RenderDoc"
            or "UI/Window" or "UI/Presenter" or "UI/D3D12" or "UI/Vulkan"
            or "GPU" or "GPU/Shader" or "GPU/D3D12" or "GPU/Vulkan"
            or "Input" or "Input/Keybinds" or "Audio";

    /// <summary>
    /// The handful of keys inside those categories that the GODOT window still reads, and which
    /// therefore move to <see cref="DisplayCategory"/> rather than being retired with the rest —
    /// see <c>GameWindowSettings.Load</c>. Retiring these would stop them being written and the
    /// game would silently fall back to a default window.
    /// </summary>
    /// <remarks>
    /// `window_width` and `window_height` are deliberately NOT here. They are the old
    /// type-in-a-number pair, replaced by the aspect and resolution dropdowns — retiring them
    /// keeps one answer to "how big is the window" rather than two that can disagree.
    /// </remarks>
    public static bool IsDisplayCVar(string name) =>
        name is "fullscreen" or "monitor" or "vsync";

    internal static string StripTomlComment(string line)
    {
        bool inString = false;
        bool escaped = false;
        var result = new StringBuilder(line.Length);
        foreach (char ch in line)
        {
            if (escaped)
            {
                result.Append(ch);
                escaped = false;
                continue;
            }

            if (ch == '\\')
            {
                result.Append(ch);
                escaped = true;
                continue;
            }

            if (ch == '"')
            {
                inString = !inString;
                result.Append(ch);
                continue;
            }

            if (ch == '#' && !inString)
            {
                break;
            }

            result.Append(ch);
        }

        return result.ToString();
    }

    internal static string UnquoteTomlString(string value)
    {
        value = value.Trim();
        if (value.Length < 2 || value[0] != '"' || value[^1] != '"')
        {
            return value;
        }

        var result = new StringBuilder(value.Length - 2);
        bool escaped = false;
        for (int i = 1; i < value.Length - 1; i++)
        {
            char ch = value[i];
            if (escaped)
            {
                result.Append(ch switch
                {
                    'n' => '\n',
                    't' => '\t',
                    'r' => '\r',
                    _ => ch,
                });
                escaped = false;
                continue;
            }

            if (ch == '\\')
            {
                escaped = true;
                continue;
            }

            result.Append(ch);
        }

        return result.ToString();
    }

    internal static string EscapeTomlString(string value)
    {
        var result = new StringBuilder(value.Length + 2);
        result.Append('"');
        foreach (char ch in value)
        {
            switch (ch)
            {
                case '\\':
                    result.Append("\\\\");
                    break;
                case '"':
                    result.Append("\\\"");
                    break;
                case '\n':
                    result.Append("\\n");
                    break;
                case '\t':
                    result.Append("\\t");
                    break;
                case '\r':
                    result.Append("\\r");
                    break;
                default:
                    result.Append(ch);
                    break;
            }
        }

        result.Append('"');
        return result.ToString();
    }

    internal static string NormalizeBoolValue(string value)
    {
        value = value.ToLowerInvariant();
        if (value is "1" or "yes" or "on")
        {
            return "true";
        }

        if (value is "0" or "no" or "off")
        {
            return "false";
        }

        return value is "true" or "false" ? value : "false";
    }

    /// <summary>
    /// Writes back every key that has no definition, instead of dropping it.
    /// </summary>
    /// <remarks>
    /// THIS FILE IS THE ONE SETTINGS FILE, so a writer that only knows how to emit the keys it
    /// has definitions for is a writer that deletes everybody else's. That is not hypothetical:
    /// the definitions are generated from the native runtime's own cvars, so anything Godot-side
    /// — the texture pipeline's settings, for one — used to survive exactly until the player next
    /// opened the settings panel and saved. The loss was silent and nothing named the key.
    ///
    /// It also protects the opposite direction: a config written by a NEWER build that knows
    /// cvars this one does not, opened by an older launcher, keeps them rather than being
    /// downgraded on the first save.
    ///
    /// The values are written back the way they came out of <see cref="ReadValues"/>, which
    /// unquoted them, so anything that is not plainly a bool or a number is re-quoted. That
    /// round trips: <see cref="ReadValues"/> unquotes again on the way back in.
    /// </remarks>
    private static void AppendUnrecognised(
        StringBuilder builder,
        IReadOnlyDictionary<string, string> values,
        HashSet<string> written)
    {
        var unrecognised = new SortedDictionary<string, string>(StringComparer.Ordinal);
        foreach ((string key, string value) in values)
        {
            // A key with a definition that ShouldWriteCVar declined is INTENTIONALLY absent —
            // it belongs to a retired category — so only keys with no definition at all belong
            // here.
            if (!written.Contains(key) && FindDefinition(key) is null)
            {
                unrecognised[key] = value;
            }
        }

        if (unrecognised.Count == 0)
        {
            return;
        }

        builder.Append('\n')
            .Append("# Other\n")
            .Append("# Keys this build has no definition for. Preserved verbatim.\n");

        foreach ((string key, string value) in unrecognised)
        {
            builder.Append(key).Append(" = ").Append(FormatUnknownValue(value)).Append('\n');
        }
    }

    private static RuntimeCVarDefinition? FindDefinition(string name)
    {
        foreach (RuntimeCVarDefinition definition in RuntimeCVarSet.All)
        {
            if (string.Equals(definition.Name, name, StringComparison.Ordinal))
            {
                return definition;
            }
        }

        return null;
    }

    /// <summary>Bools and numbers bare, everything else quoted.</summary>
    private static string FormatUnknownValue(string value)
    {
        string trimmed = value.Trim();
        if (trimmed is "true" or "false")
        {
            return trimmed;
        }

        return trimmed.Length > 0 &&
               (long.TryParse(trimmed, NumberStyles.Integer, CultureInfo.InvariantCulture, out _) ||
                double.TryParse(
                    trimmed, NumberStyles.Float, CultureInfo.InvariantCulture, out _))
            ? trimmed
            : EscapeTomlString(value);
    }

    internal static string FormatTomlValue(RuntimeCVarDefinition definition, string rawValue) =>
        definition.Type switch
        {
            RuntimeCVarType.Bool => NormalizeBoolValue(rawValue),
            RuntimeCVarType.String => EscapeTomlString(rawValue),
            _ => string.IsNullOrEmpty(rawValue) ? definition.DefaultValue : rawValue,
        };

    private static string NormalizeGameDataRootValue(string value, string configPath)
    {
        if (string.IsNullOrEmpty(value))
        {
            return value;
        }

        if (Path.IsPathRooted(value))
        {
            return ToGeneric(value);
        }

        string? configDirectory = Path.GetDirectoryName(configPath);
        if (string.IsNullOrEmpty(configDirectory))
        {
            return value;
        }

        return ToGeneric(LauncherPaths.Normalize(Path.Combine(configDirectory!, value)));
    }

    internal static string ToGeneric(string path) => path.Replace('\\', '/');
}
