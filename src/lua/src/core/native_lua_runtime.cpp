/// The workspace's own verdict on each file it produced, keyed by normalized relative path.
///
/// `_manifest.tsv` is written by the decompiler as `status<TAB>input<TAB>output<TAB>source<TAB>note`
/// with a header row. `status` is the ONLY honest signal we have about whether a reconstructed
/// script is safe to hand the guest, and the decompiler already computes it — it was simply never
/// consulted at load time.
const std::unordered_map<std::string, std::string>& GetLuaWorkspaceManifest() {
  static std::unordered_map<std::string, std::string> manifest = [] {
    std::unordered_map<std::string, std::string> entries;
    const std::filesystem::path root = GetLuaModWorkspaceRoot();
    if (root.empty()) {
      return entries;
    }

    std::ifstream stream(root / "_manifest.tsv");
    if (!stream) {
      return entries;
    }

    std::string line;
    while (std::getline(stream, line)) {
      if (!line.empty() && line.back() == '\r') {
        line.pop_back();
      }
      const std::size_t first = line.find('\t');
      if (first == std::string::npos) {
        continue;
      }
      const std::size_t second = line.find('\t', first + 1);
      if (second == std::string::npos) {
        continue;
      }

      std::string status = line.substr(0, first);
      std::string output = line.substr(second + 1, line.find('\t', second + 1) - (second + 1));
      if (status == "status" || output.empty()) {
        continue;  // header row
      }
      entries.emplace(NormalizeLuaScriptKey(std::move(output)), std::move(status));
    }

    REXLOG_INFO("Refii Lua workspace manifest: {} entries from {}", entries.size(),
                (root / "_manifest.tsv").string());
    return entries;
  }();
  return manifest;
}

/// May the guest be handed this reconstructed file?
///
/// ONLY IF THE DECOMPILER SAID IT CAME OUT EXACT. `nonexact` means the reconstruction did not
/// round-trip to the original bytecode — it is a plausible-looking Lua file that does not do the
/// same thing, and handing one to the guest is how the in-game camera disappeared: the `nonexact`
/// `scripts/camera/cameramanager.lua` never performs the setup that stands up the camera's view,
/// so the camera update found a null view and no pose was ever computed. Nothing in the logs said
/// so, because a wrong-but-valid script executes perfectly happily.
///
/// Two things are deliberately exempt:
///   - anything under `override/`, which is a HAND-WRITTEN mod. The point of the workspace is that
///     a human can put a file there and have it win; that is a deliberate act, not decompiler
///     output, and it is not the manifest's business.
///   - a workspace with no manifest at all, which is somebody's own tree rather than an installer
///     one. Refusing everything there would break a setup that never involved the decompiler.
bool LuaWorkspaceFileIsTrustworthy(const std::string& candidate) {
  if (StartsWith(candidate, "override/")) {
    return true;
  }

  const auto& manifest = GetLuaWorkspaceManifest();
  if (manifest.empty()) {
    return true;
  }

  const auto entry = manifest.find(NormalizeLuaScriptKey(candidate));
  if (entry == manifest.end()) {
    return true;  // not something the decompiler produced; leave it alone
  }

  // `copied` is a verbatim loose file and `decompiled` round-tripped exactly. Everything else —
  // `nonexact`, `aliased_nonexact`, `disassembled`, `invalid`, `budget_exceeded` — is a guess.
  return entry->second == "decompiled" || entry->second == "copied" ||
         entry->second == "aliased";
}

extern "C" int32_t refii_bridge_lua_native_mod_overrides_enabled() { return REXCVAR_GET(lua_use_mod_overrides); }

extern "C" int32_t refii_bridge_lua_native_mod_override_tracing_enabled() { return REXCVAR_GET(lua_trace_mod_overrides); }

std::filesystem::path ResolveLuaModOverridePathImpl(std::string_view script_key) {
  if (!NativeLuaModOverridesEnabled()) {
    return {};
  }

  const std::string normalized_key = NormalizeLuaScriptKey(std::string(script_key));
  if (!LooksLikeLuaScriptKey(normalized_key)) {
    return {};
  }

  const std::filesystem::path workspace_root = GetLuaModWorkspaceRoot();
  if (workspace_root.empty()) {
    return {};
  }

  for (const std::string& candidate : BuildLuaModOverrideCandidates(normalized_key)) {
    std::filesystem::path resolved_path = ResolveCaseInsensitivePath(workspace_root, candidate);
    if (resolved_path.empty()) {
      continue;
    }

    std::error_code error;
    if (!std::filesystem::is_regular_file(resolved_path, error)) {
      continue;
    }

    // The file exists — but existing is not the same as being right. Gate it on the
    // decompiler's own verdict; a `nonexact` reconstruction is worse than no override at
    // all, because the guest runs it happily and the damage shows up somewhere unrelated.
    if (!LuaWorkspaceFileIsTrustworthy(candidate)) {
      static std::mutex reported_mutex;
      static std::unordered_map<std::string, bool> reported;
      bool first = false;
      {
        std::scoped_lock lock(reported_mutex);
        first = reported.emplace(candidate, true).second;
      }
      if (first) {
        REXLOG_INFO("Refii Lua override for {} SKIPPED — the workspace manifest does not mark it "
                    "exact; using the guest's own bytecode instead",
                    candidate);
      }
      continue;
    }

    return resolved_path;
  }

  return {};
}

void RegisterNativeScriptHandler(std::string_view script_key, NativeScriptHandler handler) {
  if (script_key.empty() || handler == nullptr) {
    return;
  }

  std::scoped_lock lock(GetHandlerMutex());
  GetHandlerMap()[NormalizeLuaScriptKey(std::string(script_key))] = handler;
}

NativeDispatchResult DispatchNativeScriptImpl(PPCContext& ppc, uint8_t* base,
                                          const NativeScriptRequest& request) {
  static const bool kBuiltinHandlersRegistered = [] {
    RegisterBuiltinNativeScriptHandlers();
    return true;
  }();
  (void)kBuiltinHandlersRegistered;

  if (!NativeLuaHooksEnabled()) {
    return NativeDispatchResult::kUnhandled;
  }

  const std::string script_key = ReadNativeLuaScriptKey(base, request);
  if (script_key.empty()) {
    if (REXCVAR_GET(lua_trace_native_handlers)) {
      REXLOG_INFO("Lua native hooks enabled, but no recognizable script key was available for "
                  "guest call 0x{:08X} (chunk=0x{:08X})",
                  request.source_guest, request.chunk_name_guest);
    }
    return NativeDispatchResult::kUnhandled;
  }

  // Stage 2 (Lua volume): host-VM execution outranks hand-written handlers so
  // the generic path gets exercised where enabled; it returns kUnhandled on
  // any doubt, falling through to the tiers below.
  const NativeDispatchResult host_vm_result =
      TryExecuteScriptWithHostVm(ppc, base, request, script_key);
  if (host_vm_result != NativeDispatchResult::kUnhandled) {
    if (REXCVAR_GET(lua_trace_native_handlers)) {
      REXLOG_INFO("Lua host VM {} for {}",
                  host_vm_result == NativeDispatchResult::kHandledSuccess ? "succeeded" : "failed",
                  script_key);
    }
    return host_vm_result;
  }

  NativeScriptHandler handler = nullptr;
  {
    std::scoped_lock lock(GetHandlerMutex());
    handler = FindHandlerLocked(script_key);
  }

  if (handler == nullptr) {
    if (REXCVAR_GET(lua_trace_native_handlers)) {
      REXLOG_INFO("Lua native hook fallback for {}", script_key);
    }
    return NativeDispatchResult::kUnhandled;
  }

  const NativeScriptExecution execution{
      .ppc = ppc,
      .base = base,
      .request = request,
      .script_key = script_key,
  };

  const bool handled_successfully = handler(execution);
  if (REXCVAR_GET(lua_trace_native_handlers)) {
    REXLOG_INFO("Lua native handler {} for {}", handled_successfully ? "succeeded" : "failed",
                script_key);
  }

  return handled_successfully ? NativeDispatchResult::kHandledSuccess
                              : NativeDispatchResult::kHandledFailure;
}


// --- The payload/host C ABI ----------------------------------------------------------
//
// Entries for the inline wrappers in core/native_lua_hooks.h. The C++ implementations above
// keep their shape for host callers; only the boundary is flattened. Strings go into the
// CALLER's buffer with the needed length returned, so nothing allocated here is freed on
// the other side. See core/lua_payload_bridge.h.

namespace {

size_t LuaCopyOut(const std::string& value, char* out, size_t capacity) {
  if (out != nullptr && capacity > 0) {
    size_t take = value.size() < capacity ? value.size() : capacity;
    std::memcpy(out, value.data(), take);
  }
  return value.size();
}

}  // namespace

extern "C" size_t refii_bridge_lua_read_guest_lua_string_like(uint8_t* base, uint32_t guest_ptr,
                                                              size_t max_bytes, char* out,
                                                              size_t capacity) {
  return LuaCopyOut(ReadGuestLuaStringLikeImpl(base, guest_ptr, max_bytes), out, capacity);
}

extern "C" size_t refii_bridge_lua_read_native_script_key(uint8_t* base,
                                                          const NativeScriptRequest* request,
                                                          char* out, size_t capacity) {
  if (request == nullptr) {
    return 0;
  }
  return LuaCopyOut(ReadNativeLuaScriptKeyImpl(base, *request), out, capacity);
}

extern "C" size_t refii_bridge_lua_resolve_mod_override_path(const char* script_key,
                                                             size_t length, char* out,
                                                             size_t capacity) {
  return LuaCopyOut(ResolveLuaModOverridePathImpl(std::string_view(script_key, length)).string(),
                    out, capacity);
}

extern "C" int32_t refii_bridge_lua_dispatch_native_script(PPCContext* ppc, uint8_t* base,
                                                           const NativeScriptRequest* request) {
  if (ppc == nullptr || request == nullptr) {
    return static_cast<int32_t>(NativeDispatchResult::kUnhandled);
  }
  return static_cast<int32_t>(DispatchNativeScriptImpl(*ppc, base, *request));
}

