bool StartsWith(std::string_view value, std::string_view prefix) {
  return value.size() >= prefix.size() && value.substr(0, prefix.size()) == prefix;
}

bool LooksLikeReadableGuestString(std::string_view value) {
  if (value.empty()) {
    return false;
  }

  for (const unsigned char ch : value) {
    if (ch == '\t' || ch == '\r' || ch == '\n') {
      continue;
    }
    if (ch < 0x20 || ch > 0x7E) {
      return false;
    }
  }

  return true;
}

int ScoreReadableGuestString(std::string_view value) {
  if (!LooksLikeReadableGuestString(value)) {
    return 0;
  }

  int score = 1;
  if (value.find(".lua") != std::string_view::npos) {
    score += 4;
  }
  if (value.find("scripts") != std::string_view::npos ||
      value.find("game:\\") != std::string_view::npos ||
      value.find("data\\") != std::string_view::npos ||
      value.find('\\') != std::string_view::npos ||
      value.find('/') != std::string_view::npos) {
    score += 2;
  }
  if (value.size() >= 16) {
    score += 1;
  }
  return score;
}

bool LooksLikeLuaScriptKey(std::string_view key) {
  if (key.empty() || key.find(".lua") == std::string_view::npos) {
    return false;
  }

  for (const unsigned char ch : key) {
    if (std::isalnum(ch) || ch == '/' || ch == '\\' || ch == '.' || ch == '_' || ch == '-' ||
        ch == '@' || ch == ':' || ch == ' ') {
      continue;
    }
    return false;
  }

  return true;
}

void AppendUnique(std::vector<std::string>& values, std::string value) {
  if (value.empty()) {
    return;
  }

  while (!value.empty() && value.front() == '/') {
    value.erase(value.begin());
  }

  if (value.empty()) {
    return;
  }

  if (std::find(values.begin(), values.end(), value) == values.end()) {
    values.push_back(std::move(value));
  }
}

std::filesystem::path ResolveCaseInsensitivePath(const std::filesystem::path& root,
                                                 std::string_view relative_path) {
  std::error_code error;
  if (root.empty() || !std::filesystem::exists(root, error) ||
      !std::filesystem::is_directory(root, error)) {
    return {};
  }

  std::filesystem::path current = root;
  size_t position = 0;
  while (position < relative_path.size()) {
    const size_t next_separator = relative_path.find('/', position);
    const size_t count =
        next_separator == std::string_view::npos ? relative_path.size() - position
                                                 : next_separator - position;
    const std::string_view component = relative_path.substr(position, count);
    position = next_separator == std::string_view::npos ? relative_path.size() : next_separator + 1;

    if (component.empty() || component == ".") {
      continue;
    }

    const std::filesystem::path exact = current / std::string(component);
    if (std::filesystem::exists(exact, error)) {
      current = exact;
      continue;
    }

    if (!std::filesystem::is_directory(current, error)) {
      return {};
    }

    std::filesystem::path match;
    const std::string lowered_component = NormalizeLuaScriptKey(std::string(component));
    for (std::filesystem::directory_iterator iterator(current, error), end; iterator != end;
         iterator.increment(error)) {
      if (NormalizeLuaScriptKey(iterator->path().filename().string()) == lowered_component) {
        match = iterator->path();
        break;
      }
    }

    if (error || match.empty()) {
      return {};
    }

    current = std::move(match);
  }

  return std::filesystem::exists(current, error) ? current : std::filesystem::path{};
}

uint32_t ReadGuestLE32(uint8_t* base, uint32_t guest_address) {
  return uint32_t(PpcLoadU8(base, guest_address)) |
         (uint32_t(PpcLoadU8(base, guest_address + 1)) << 8) |
         (uint32_t(PpcLoadU8(base, guest_address + 2)) << 16) |
         (uint32_t(PpcLoadU8(base, guest_address + 3)) << 24);
}

std::string ReadGuestSizedString(uint8_t* base, uint32_t data_guest, uint32_t length,
                                 size_t max_bytes) {
  if (data_guest == 0 || length == 0 || length > 0x10000) {
    return {};
  }

  std::string value;
  const size_t clamped_length = std::min<size_t>(length, max_bytes);
  value.reserve(clamped_length);
  for (size_t i = 0; i < clamped_length; ++i) {
    value.push_back(static_cast<char>(
        PpcLoadU8(base, data_guest + static_cast<uint32_t>(i))));
  }

  while (!value.empty() && value.back() == '\0') {
    value.pop_back();
  }

  return LooksLikeReadableGuestString(value) ? value : std::string{};
}

std::string ReadGuestStringObject(uint8_t* base, uint32_t object_guest, size_t max_bytes) {
  if (object_guest == 0) {
    return {};
  }

  const uint32_t data_guest = PpcLoadU32(base, object_guest + 0);
  const uint32_t length = PpcLoadU32(base, object_guest + 4);
  return ReadGuestSizedString(base, data_guest, length, max_bytes);
}

std::string ReadGuestLua51TStringObject(uint8_t* base, uint32_t object_guest, size_t max_bytes) {
  if (base == nullptr || object_guest == 0) {
    return {};
  }

  // Guest stack string values point at a real Lua 5.1 TString object:
  // CommonHeader (next, tt, marked), reserved, hash, len, then inline chars.
  constexpr uint32_t kLua51StringTagOffset = 4;
  constexpr uint32_t kLua51StringLengthOffset = 12;
  constexpr uint32_t kLua51StringCharsOffset = 16;
  constexpr uint8_t kLuaTString = 4;

  if (PpcLoadU8(base, object_guest + kLua51StringTagOffset) != kLuaTString) {
    return {};
  }

  const uint32_t length = PpcLoadU32(base, object_guest + kLua51StringLengthOffset);
  return ReadGuestSizedString(base,
                              object_guest + kLua51StringCharsOffset,
                              length,
                              max_bytes);
}

std::string ReadGuestWrappedString(uint8_t* base, uint32_t wrapper_guest, size_t max_bytes) {
  if (wrapper_guest == 0) {
    return {};
  }

  const uint32_t object_guest = PpcLoadU32(base, wrapper_guest + 0);
  return ReadGuestStringObject(base, object_guest, max_bytes);
}

uint64_t HashBytes(const uint8_t* bytes, size_t size) {
  constexpr uint64_t kFnvOffset = 1469598103934665603ull;
  constexpr uint64_t kFnvPrime = 1099511628211ull;

  uint64_t hash = kFnvOffset;
  for (size_t i = 0; i < size; ++i) {
    hash ^= uint64_t(bytes[i]);
    hash *= kFnvPrime;
  }
  return hash;
}

uint64_t HashGuestBytes(uint8_t* base, uint32_t guest_address, uint32_t size) {
  constexpr uint64_t kFnvOffset = 1469598103934665603ull;
  constexpr uint64_t kFnvPrime = 1099511628211ull;

  uint64_t hash = kFnvOffset;
  for (uint32_t i = 0; i < size; ++i) {
    hash ^= uint64_t(PpcLoadU8(base, guest_address + i));
    hash *= kFnvPrime;
  }
  return hash;
}

std::string ReadLuaBytecodeSourcePath(uint8_t* base, const NativeScriptRequest& request) {
  if (request.script_buffer_guest == 0 || request.script_size < 16) {
    return {};
  }

  const uint32_t chunk = request.script_buffer_guest;
  if (PpcLoadU8(base, chunk) != 0x1B || PpcLoadU8(base, chunk + 1) != 'L' ||
      PpcLoadU8(base, chunk + 2) != 'u' ||
      PpcLoadU8(base, chunk + 3) != 'a') {
    return {};
  }

  if (PpcLoadU8(base, chunk + 4) != 0x51 ||
      PpcLoadU8(base, chunk + 6) != 0x01 ||
      PpcLoadU8(base, chunk + 8) != 0x04) {
    return {};
  }

  const uint32_t source_size = ReadGuestLE32(base, chunk + 12);
  if (source_size <= 1 || source_size > request.script_size - 16 || source_size > 4096) {
    return {};
  }

  std::string source;
  source.reserve(source_size);
  for (uint32_t i = 0; i < source_size - 1; ++i) {
    source.push_back(static_cast<char>(PpcLoadU8(base, chunk + 16 + i)));
  }
  return NormalizeLuaScriptKey(source);
}

std::filesystem::path GetLuaModWorkspaceRoot() {
  auto get_default_workspace_base = []() -> std::filesystem::path {
    const auto* runtime = rex::Runtime::instance();
    if (runtime == nullptr) {
      return {};
    }

    std::filesystem::path base = runtime->game_data_root();
    if (NormalizeLuaScriptKey(base.filename().generic_string()) == "data") {
      base = base.parent_path();
    }
    if (NormalizeLuaScriptKey(base.filename().generic_string()) == "game") {
      base = base.parent_path();
    }
    return base;
  };

  std::filesystem::path root;
  if (!REXCVAR_GET(lua_mod_workspace_root).empty()) {
    root = std::filesystem::path(REXCVAR_GET(lua_mod_workspace_root));
    if (root.is_relative()) {
      const std::filesystem::path base = get_default_workspace_base();
      if (!base.empty()) {
        root = base / root;
      }
    }
  } else {
    const std::filesystem::path base = get_default_workspace_base();
    if (!base.empty()) {
      root = base / "unpacked";
    }
  }

  return root.lexically_normal();
}

std::string MakeWorkspaceScriptKey(const std::filesystem::path& workspace_root,
                                   const std::filesystem::path& script_path) {
  std::error_code error;
  const std::filesystem::path relative_path = std::filesystem::relative(script_path, workspace_root, error);
  if (error || relative_path.empty()) {
    return {};
  }

  const std::string relative = NormalizeLuaScriptKey(
      refii::lua::CanonicalizeRetailLuaRelativeString(relative_path.generic_string()));
  constexpr std::string_view kGameScriptsPrefix = "gamescripts/scripts/";
  constexpr std::string_view kGuiScriptsPrefix = "guiscripts/scripts/";
  constexpr std::string_view kGuiArtPrefix = "guiscripts/art/";
  constexpr std::string_view kLooseScriptsPrefix = "scripts/";

  if (StartsWith(relative, kGameScriptsPrefix)) {
    return "scripts/" + relative.substr(kGameScriptsPrefix.size());
  }
  if (StartsWith(relative, kGuiScriptsPrefix)) {
    return "scripts/" + relative.substr(kGuiScriptsPrefix.size());
  }
  if (StartsWith(relative, kGuiArtPrefix)) {
    return "art/" + relative.substr(kGuiArtPrefix.size());
  }
  if (StartsWith(relative, kLooseScriptsPrefix)) {
    return "data/scripts/" + relative.substr(kLooseScriptsPrefix.size());
  }

  return {};
}

void BuildLuaBytecodeHashMap() {
  const std::filesystem::path workspace_root = GetLuaModWorkspaceRoot();
  std::filesystem::path hash_root = workspace_root / "luasource";
  std::error_code error;
  if (workspace_root.empty()) {
    return;
  }

  if (!std::filesystem::exists(hash_root, error) || !std::filesystem::is_directory(hash_root, error)) {
    hash_root = workspace_root;
  }

  if (!std::filesystem::exists(hash_root, error)) {
    return;
  }

  auto& hash_map = GetBytecodeHashMap();
  for (std::filesystem::recursive_directory_iterator iterator(hash_root, error), end; iterator != end;
       iterator.increment(error)) {
    if (error || !iterator->is_regular_file(error) || iterator->path().extension() != ".lua") {
      continue;
    }

    const std::string script_key = MakeWorkspaceScriptKey(hash_root, iterator->path());
    if (script_key.empty()) {
      continue;
    }

    std::ifstream stream(iterator->path(), std::ios::binary);
    if (!stream) {
      continue;
    }

    stream.seekg(0, std::ios::end);
    const std::streampos size = stream.tellg();
    if (size <= 0) {
      continue;
    }

    stream.seekg(0, std::ios::beg);
    std::vector<uint8_t> bytes(static_cast<size_t>(size));
    stream.read(reinterpret_cast<char*>(bytes.data()), static_cast<std::streamsize>(bytes.size()));
    if (!stream && !stream.eof()) {
      continue;
    }

    const uint64_t hash = HashBytes(bytes.data(), bytes.size());
    hash_map.try_emplace(hash, script_key);
  }
}

std::string LookupLuaWorkspaceScriptKeyByHash(uint8_t* base, const NativeScriptRequest& request) {
  if (request.script_buffer_guest == 0 || request.script_size == 0) {
    return {};
  }

  std::call_once(GetBytecodeHashMapInitFlag(), BuildLuaBytecodeHashMap);
  const auto& hash_map = GetBytecodeHashMap();
  if (hash_map.empty()) {
    return {};
  }

  const uint64_t hash = HashGuestBytes(base, request.script_buffer_guest, request.script_size);
  if (const auto it = hash_map.find(hash); it != hash_map.end()) {
    return it->second;
  }

  return {};
}

std::vector<std::string> BuildLuaModOverrideCandidates(std::string_view script_key) {
  const auto append_canonical = [](std::vector<std::string>& values, std::string value) {
    AppendUnique(values, refii::lua::CanonicalizeRetailLuaRelativeString(value));
  };

  std::vector<std::string> relatives;
  append_canonical(relatives, std::string(script_key));

  if (StartsWith(script_key, "data/")) {
    append_canonical(relatives, std::string(script_key.substr(5)));
  }

  if (StartsWith(script_key, "data/scripts/")) {
    append_canonical(
        relatives, "scripts/" + std::string(script_key.substr(sizeof("data/scripts/") - 1)));
  }

  if (StartsWith(script_key, "data/scripts_r/")) {
    const std::string tail = std::string(script_key.substr(sizeof("data/scripts_r/") - 1));
    append_canonical(relatives, "scripts_r/" + tail);
    append_canonical(relatives, "scripts/" + tail);
  }

  std::vector<std::string> candidates;
  for (const std::string& relative : relatives) {
    append_canonical(candidates, "override/" + relative);
    append_canonical(candidates, relative);

    if (StartsWith(relative, "scripts/")) {
      append_canonical(candidates, "gamescripts/" + relative);
      append_canonical(candidates, "gamescripts_r/" + relative);
      append_canonical(candidates, "guiscripts/" + relative);
      continue;
    }

    if (StartsWith(relative, "scripts_r/")) {
      const std::string tail =
          std::string(std::string_view(relative).substr(sizeof("scripts_r/") - 1));
      append_canonical(candidates, "gamescripts_r/scripts/" + tail);
      append_canonical(candidates, "gamescripts/scripts/" + tail);
      continue;
    }

    if (StartsWith(relative, "art/")) {
      append_canonical(candidates, "guiscripts/" + relative);
    }
  }

  return candidates;
}

std::string CanonicalizeLuaScriptKeyCandidate(std::string key) {
  key = NormalizeLuaScriptKey(
      refii::lua::CanonicalizeRetailLuaRelativeString(std::move(key)));

  constexpr std::string_view kOverridePrefix = "override/";
  constexpr std::string_view kGameScriptsPrefix = "gamescripts/scripts/";
  constexpr std::string_view kGuiScriptsPrefix = "guiscripts/scripts/";
  constexpr std::string_view kGuiArtPrefix = "guiscripts/art/";

  if (StartsWith(key, kOverridePrefix)) {
    key = key.substr(kOverridePrefix.size());
  }

  if (StartsWith(key, kGameScriptsPrefix)) {
    return "scripts/" + key.substr(kGameScriptsPrefix.size());
  }
  if (StartsWith(key, kGuiScriptsPrefix)) {
    return "scripts/" + key.substr(kGuiScriptsPrefix.size());
  }
  if (StartsWith(key, kGuiArtPrefix)) {
    return "art/" + key.substr(kGuiArtPrefix.size());
  }

  return key;
}

std::string ExtractEmbeddedLuaScriptKey(std::string_view value) {
  if (value.empty()) {
    return {};
  }

  const std::string normalized = NormalizeLuaScriptKey(std::string(value));
  if (normalized.empty()) {
    return {};
  }

  const std::string canonical = CanonicalizeLuaScriptKeyCandidate(normalized);
  if (LooksLikeLuaScriptKey(canonical)) {
    return canonical;
  }

  constexpr std::string_view kCandidatePrefixes[] = {
      "data/scripts/",      "data/scripts_r/",      "scripts/",        "scripts_r/",
      "gamescripts/scripts/", "gamescripts_r/scripts/", "guiscripts/scripts/",
      "guiscripts/art/",    "art/"};

  for (const std::string_view prefix : kCandidatePrefixes) {
    size_t search_from = 0;
    while (true) {
      const size_t start = normalized.find(prefix, search_from);
      if (start == std::string::npos) {
        break;
      }

      const size_t lua_suffix = normalized.find(".lua", start);
      if (lua_suffix != std::string::npos) {
        std::string candidate = CanonicalizeLuaScriptKeyCandidate(
            normalized.substr(start, lua_suffix + 4 - start));
        if (LooksLikeLuaScriptKey(candidate)) {
          return candidate;
        }
      }

      search_from = start + 1;
    }
  }

  return {};
}

std::string ReadValidatedLuaScriptKey(uint8_t* base, const NativeScriptRequest& request) {
  const std::string source = ExtractEmbeddedLuaScriptKey(
      ReadGuestLuaStringLike(base, request.source_guest));
  if (LooksLikeLuaScriptKey(source)) {
    return source;
  }

  const std::string chunk_name = ExtractEmbeddedLuaScriptKey(
      ReadGuestLuaStringLike(base, request.chunk_name_guest));
  if (LooksLikeLuaScriptKey(chunk_name)) {
    return chunk_name;
  }

  const std::string bytecode_source =
      CanonicalizeLuaScriptKeyCandidate(ReadLuaBytecodeSourcePath(base, request));
  if (LooksLikeLuaScriptKey(bytecode_source)) {
    return bytecode_source;
  }

  const std::string workspace_match =
      CanonicalizeLuaScriptKeyCandidate(LookupLuaWorkspaceScriptKeyByHash(base, request));
  if (LooksLikeLuaScriptKey(workspace_match)) {
    return workspace_match;
  }

  return {};
}

